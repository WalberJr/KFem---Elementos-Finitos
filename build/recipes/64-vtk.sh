#!/usr/bin/env bash
# VTK com módulo Qt e wrappers Python (renderização OpenGL do sistema).
. "$(dirname "$0")/_common.sh"; begin vtk "VTK-${VTK_VERSION}.tar.gz"
cmake -B b -G Ninja -DCMAKE_BUILD_TYPE=Release -DCMAKE_INSTALL_PREFIX="$KFEM_SDK" \
  -DCMAKE_C_COMPILER_LAUNCHER=ccache -DCMAKE_CXX_COMPILER_LAUNCHER=ccache -DCMAKE_C_COMPILER=gcc -DCMAKE_CXX_COMPILER=g++ \
  -DVTK_WRAP_PYTHON=ON -DVTK_PYTHON_VERSION=3 -DPython3_EXECUTABLE="$KFEM_SDK/bin/python3" \
  -DVTK_GROUP_ENABLE_Qt=YES -DVTK_MODULE_ENABLE_VTK_GUISupportQtSQL=NO -DVTK_MODULE_ENABLE_VTK_GUISupportQtQuick=NO -DVTK_MODULE_ENABLE_VTK_GUISupportQt=YES -DVTK_QT_VERSION=6 -DQt6_DIR="$KFEM_SDK/qt6/lib/cmake/Qt6" \
  -DVTK_GROUP_ENABLE_Rendering=YES -DVTK_GROUP_ENABLE_StandAlone=YES -DVTK_GROUP_ENABLE_Imaging=DEFAULT \
  -DVTK_GROUP_ENABLE_Web=NO -DVTK_GROUP_ENABLE_MPI=NO -DVTK_USE_MPI=OFF -DVTK_BUILD_TESTING=OFF -DVTK_BUILD_EXAMPLES=OFF \
  -DVTK_MODULE_ENABLE_VTK_IOXdmf2=NO -DVTK_MODULE_ENABLE_VTK_IOCesium3DTiles=NO -DVTK_MODULE_ENABLE_VTK_IOCGNSReader=NO -DVTK_MODULE_ENABLE_VTK_IOADIOS2=NO -DVTK_ENABLE_WRAPPING=ON \
  -DVTK_OPENGL_HAS_EGL=OFF -DVTK_USE_X=ON -DVTK_DEFAULT_RENDER_WINDOW_OFFSCREEN=OFF -DVTK_SMP_IMPLEMENTATION_TYPE=OpenMP
cmake --build b; cmake --install b
pycheck "import vtk; print('vtk', vtk.vtkVersion.GetVTKVersion())"; finish
